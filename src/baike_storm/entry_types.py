# 线上没有航天器大类(嫦娥六号会被路由到「仪器设备」),按标题兜底识别。
_SPACE_RE = re.compile(r"(号|卫星|探测器|飞船|火箭|空间站|着陆器|月球车|火星车|望远镜)$|^(嫦娥|天问|神舟|天宫|天舟|长征|北斗)")


def type_group(title: str, dalei: str | None) -> str:
    if _SPACE_RE.search(title or "") and (not dalei or DALEI_TO_GROUP.get(dalei) in (None, "product")):
        return "space"
    return DALEI_TO_GROUP.get(dalei or "", "generic")
